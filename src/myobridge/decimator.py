"""Optional 2x oversampling: sample at 2 kHz, filter, keep every 2nd sample.

Why: the MyoWare's RAW output only rolls off gently above ~500 Hz, so at a
1 kHz sample rate a lot of wideband noise folds back into the EMG band
(docs/ALIASING.md). Sampling at 2 kHz pushes the fold-over point to 1 kHz;
a digital low-pass then removes 500-1000 Hz before we drop to 1 kHz, so the
PC still receives 1 kHz data and nothing else changes.

The filter is a 47-tap *halfband* FIR: every second coefficient is exactly
zero and the centre one is exactly 1/2, leaving 25 non-zero taps. They are
symmetric, so one output sample costs 13 multiplies (12 pairs + the centre).
It runs on the ESP32 in integer maths (firmware/.../mb_decimator.h).
This module is the bit-exact Python reference that the firmware is tested
against: same Q15 coefficients, same rounding, same saturation.

Integer details (identical in C++):
    acc = sum_k H[k] * x[n - k]             (32-bit is enough: |acc| < 1.76e9)
    y   = (acc + 2**14) >> 15               (round half up, arithmetic shift)
    y   = clamp(y, -32768, 32767)
"""

from __future__ import annotations

import numpy as np
from numpy.typing import ArrayLike, NDArray
from scipy import signal

N_TAPS = 47
KAISER_BETA = 6.0
Q = 15

# Generated by design_halfband(); test_decimator checks the two agree and that
# the firmware header holds the same numbers.
HALFBAND_Q15 = np.array(
    [-7, 0, 23, 0, -55, 0, 107, 0, -189, 0, 311, 0, -489, 0, 750, 0, -1150, 0, 1830, 0, -3318, 0]
    + [10377, 16384, 10377]
    + [0, -3318, 0, 1830, 0, -1150, 0, 750, 0, -489, 0, 311, 0, -189, 0, 107, 0, -55, 0, 23, 0, -7],
    dtype=np.int64,
)


def design_halfband(n_taps: int = N_TAPS, beta: float = KAISER_BETA) -> NDArray[np.int64]:
    """Kaiser-windowed sinc at half the input Nyquist, quantised to Q15.

    A sinc cut at exactly fs/4 is zero at every even offset from the centre,
    which is what makes it a halfband; quantisation keeps those zeros, and we
    pin the centre to exactly 0.5.
    """
    if n_taps % 4 != 3:
        raise ValueError("n_taps must be 4k + 3 (with 4k + 1 both end taps are zero)")
    h = signal.firwin(n_taps, 0.5, window=("kaiser", beta))
    q = np.round(h * 2**Q).astype(np.int64)
    q[n_taps // 2] = 2 ** (Q - 1)
    out: NDArray[np.int64] = q
    return out


def _round_shift(acc: NDArray[np.int64]) -> NDArray[np.int16]:
    y = (acc + (1 << (Q - 1))) >> Q
    out: NDArray[np.int16] = np.clip(y, -32768, 32767).astype(np.int16)
    return out


def decimate2(x: ArrayLike, taps: NDArray[np.int64] = HALFBAND_Q15) -> NDArray[np.int16]:
    """Decimate a whole (n_samples, n_channels) int16 recording by 2.

    Output m is the filter evaluated at input sample 2m + 1, starting from an
    all-zero history (exactly what the streaming version does after reset).
    """
    xa = np.asarray(x)
    if xa.ndim != 2 or xa.dtype != np.int16:
        raise ValueError("x must be a 2-D int16 array (n_samples, n_channels)")
    if len(xa) % 2:
        raise ValueError("need an even number of samples")
    xi = xa.astype(np.int64)
    n = len(taps)
    padded = np.vstack([np.zeros((n - 1, xi.shape[1]), dtype=np.int64), xi])
    # full[i] = sum_k taps[k] * x[i - k]; integer convolution, no rounding until the end
    full = np.stack(
        [np.convolve(padded[:, c], taps, mode="valid") for c in range(xi.shape[1])], axis=1
    )
    return _round_shift(full[1::2])


class HalfbandDecimator:
    """Streaming version: push pairs of samples, get one sample back per pair.

    Mirrors the firmware's MbHalfbandDecimator one step at a time; it exists
    to make "the firmware loop does the same thing" easy to see and test.
    """

    def __init__(self, n_channels: int, taps: NDArray[np.int64] = HALFBAND_Q15):
        self.taps = taps
        self.history = np.zeros((len(taps), n_channels), dtype=np.int64)  # [0] = newest

    def push(self, first: ArrayLike, second: ArrayLike) -> NDArray[np.int16]:
        for sample in (first, second):
            self.history = np.roll(self.history, 1, axis=0)
            self.history[0] = np.asarray(sample, dtype=np.int64)
        acc = self.taps @ self.history
        return _round_shift(acc)
